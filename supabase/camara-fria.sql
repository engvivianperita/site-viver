-- VIVER Câmara Fria. Estruturas isoladas; nenhuma tabela existente é removida.
begin;
create table if not exists public.cf_companies(id uuid primary key,name text not null,cnpj text,unit text,procedure text,contact text);
create table if not exists public.cf_users(id uuid primary key,name text not null,email text unique not null,password text not null,role text not null check(role in ('admin','student')),company uuid references public.cf_companies(id),job text,change_password integer not null default 1,active integer not null default 1,auth_version integer not null default 1);
create table if not exists public.cf_sessions(token text primary key,"user" uuid references public.cf_users(id),expires bigint not null,auth_version integer not null);
create table if not exists public.cf_progress("user" uuid references public.cf_users(id),lesson integer check(lesson between 1 and 20),seconds integer not null default 0,last_ping bigint,completed timestamptz,primary key("user",lesson));
create table if not exists public.cf_attempts(id bigint generated by default as identity primary key,"user" uuid references public.cf_users(id),lesson integer,answer integer,correct integer,created timestamptz default now(),version text);
create table if not exists public.cf_certificates(id uuid primary key,"user" uuid references public.cf_users(id),snapshot jsonb,created timestamptz default now(),revoked integer default 0);
create table if not exists public.cf_audit(id bigint generated by default as identity primary key,actor uuid,event text,detail text,created timestamptz default now());
create table if not exists public.cf_rate_limits(key text primary key,n integer not null,until_at bigint not null);
create index if not exists cf_sessions_expiry on public.cf_sessions(expires);
create index if not exists cf_certificates_user on public.cf_certificates("user");
create index if not exists cf_attempts_user on public.cf_attempts("user",lesson);
alter table public.cf_companies enable row level security;
alter table public.cf_users enable row level security;
alter table public.cf_sessions enable row level security;
alter table public.cf_progress enable row level security;
alter table public.cf_attempts enable row level security;
alter table public.cf_certificates enable row level security;
alter table public.cf_audit enable row level security;
alter table public.cf_rate_limits enable row level security;
revoke all on public.cf_companies,public.cf_users,public.cf_sessions,public.cf_progress,public.cf_attempts,public.cf_certificates,public.cf_audit,public.cf_rate_limits from anon,authenticated;
grant all on public.cf_companies,public.cf_users,public.cf_sessions,public.cf_progress,public.cf_attempts,public.cf_certificates,public.cf_audit,public.cf_rate_limits to service_role;
grant usage,select on sequence public.cf_attempts_id_seq,public.cf_audit_id_seq to service_role;

create or replace function public.cf_limit(p_key text,p_now bigint) returns boolean language plpgsql security invoker set search_path=public as $$
declare tries integer;
begin
 insert into cf_rate_limits(key,n,until_at) values(p_key,1,p_now+900000)
 on conflict(key) do update set n=case when cf_rate_limits.until_at<p_now then 1 else cf_rate_limits.n+1 end,until_at=case when cf_rate_limits.until_at<p_now then p_now+900000 else cf_rate_limits.until_at end returning n into tries;
 return tries<=15;
end $$;

create or replace function public.cf_ping(p_user uuid,p_lesson integer,p_now bigint) returns integer language plpgsql security invoker set search_path=public as $$
declare result integer;
begin
 if p_lesson not between 1 and 20 then raise exception 'Aula inválida'; end if;
 if p_lesson>1 and not exists(select 1 from cf_progress where "user"=p_user and lesson=p_lesson-1 and completed is not null) then raise exception 'Conclua a aula anterior'; end if;
 insert into cf_progress("user",lesson,seconds,last_ping) values(p_user,p_lesson,0,p_now)
 on conflict("user",lesson) do update set seconds=cf_progress.seconds+case when p_now-cf_progress.last_ping between 8000 and 35000 then floor((p_now-cf_progress.last_ping)/1000.0)::integer else 0 end,last_ping=p_now returning seconds into result;
 return result;
end $$;

create or replace function public.cf_answer(p_user uuid,p_lesson integer,p_answer integer,p_correct boolean,p_version text) returns void language plpgsql security invoker set search_path=public as $$
declare spent integer;
begin
 if p_lesson>1 and not exists(select 1 from cf_progress where "user"=p_user and lesson=p_lesson-1 and completed is not null) then raise exception 'Conclua a aula anterior'; end if;
 select seconds into spent from cf_progress where "user"=p_user and lesson=p_lesson for update;
 if spent is null or spent<20 then raise exception 'Leia o assunto antes de responder'; end if;
 insert into cf_attempts("user",lesson,answer,correct,version) values(p_user,p_lesson,p_answer,case when p_correct then 1 else 0 end,p_version);
 if p_correct then update cf_progress set completed=coalesce(completed,now()) where "user"=p_user and lesson=p_lesson; end if;
end $$;

create or replace function public.cf_password(p_user uuid,p_hash text,p_temporary integer) returns void language plpgsql security invoker set search_path=public as $$
begin
 update cf_users set password=p_hash,change_password=p_temporary,auth_version=auth_version+1 where id=p_user;
 delete from cf_sessions where "user"=p_user;
end $$;
revoke all on function public.cf_limit(text,bigint),public.cf_ping(uuid,integer,bigint),public.cf_answer(uuid,integer,integer,boolean,text),public.cf_password(uuid,text,integer) from public,anon,authenticated;
grant execute on function public.cf_limit(text,bigint),public.cf_ping(uuid,integer,bigint),public.cf_answer(uuid,integer,integer,boolean,text),public.cf_password(uuid,text,integer) to service_role;
commit;

create table if not exists public.cf_final_exams(id uuid primary key,"user" uuid not null references public.cf_users(id),actor uuid not null references public.cf_users(id),created timestamptz not null default now(),version text not null,answers jsonb not null,score integer not null check(score between 0 and 100),passed boolean not null);
alter table public.cf_final_exams enable row level security;
revoke all on public.cf_final_exams from anon,authenticated;
grant all on public.cf_final_exams to service_role;
